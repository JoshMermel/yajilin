// Write docs/how_to_solve.md: every rule the Hint button knows, in the order a person meets them (cheapest first), each with a screenshot
// of a position where Hint shows it. The screenshots link to the hidden "armory" book so a reader can open the same puzzle and try it.
//
// The pieces:  node tools/how_to_examples.mjs scan, build   find the examples and write data/armory.csv + docs/examples/examples.json
//              tools/capture_how_to_images.py             take the screenshots (docs/images/<rule>.png)
//              node tools/build_how_to_solve.mjs          this file: the markdown (rule descriptions come from the README's rules table)
import fs from 'node:fs';
import { RULES, TIERS, TIER_INFO } from '../js/rating.js';

const root = new URL('..', import.meta.url).pathname;
const SITE = 'https://joshmermelstein.com/yajilin/index.html';
const examples = JSON.parse(fs.readFileSync(root + 'docs/examples/examples.json', 'utf8'));
const byRule = new Map(examples.map((e) => [e.rule, e]));

// "| 18 | `boxStarvesClue` | what it does | Medium | 16 |" -> { boxStarvesClue: 'what it does' }
const cap = (t) => t.charAt(0).toUpperCase() + t.slice(1);
const about = {};
for (const line of fs.readFileSync(root + 'README.md', 'utf8').split('\n')) {
  const m = line.match(/^\| \d+ \| `(\w+)` \| (.*) \| (?:Beginner|Medium|Hard) \| \d+ \|$/);
  if (m) about[m[1]] = cap(m[2]);
}

const NO_EXAMPLE = {
  noEarlyClose: 'It only ever rules a segment out ("no line joins these two ends"), and the Hint button has nothing to show for that, since you cannot mark "no segment". It appears in a hint as the "Relies on" line instead, and `sameSegmentExits` and `closingCell` are its two visible forms.',
  crossingParity: 'It is rare enough that none of the puzzles I searched shows it as the next hint.',
  regionPairs: 'It applies to puzzles with regions, and none of the regional puzzles I searched shows it as the next hint.',
};

const ex = (rule) => {
  const e = byRule.get(rule.id);
  const link = `${SITE}?book=armory&puzzle=${e.puzzle}`;
  const presses = e.hints === 0 ? 'the empty board' : `the board after ${e.hints} earlier hint${e.hints === 1 ? '' : 's'}`;
  return [
    `<a href="${link}">`,
    `<img src="images/${rule.id}.png" width="480" alt="${rule.id}"></a>`,
    '',
    `*${e.name}, ${e.rows}×${e.cols}: ${presses}. Click the picture to open this puzzle and press Hint yourself.*`,
    '',
    `Hint says: "${e.text}"`,
    '',
  ];
};

const out = [];
const say = (...lines) => out.push(...lines);

say(
  '# How to solve',
  '',
  '<!-- Generated by tools/build_how_to_solve.mjs from the rules table in js/rating.js, README.md and the pictures in docs/images. -->',
  '',
  'Every technique the Hint button knows, with a picture of it at work. It is a guide for new players, and a reference for how the hint',
  'system and the difficulty rating think (they are the same machinery: see "Difficulty: rules, tiers and score" in the [README](../README.md)).',
  '',
  '## The rules of the puzzle',
  '',
  '- Draw one closed loop that goes through every cell that is not a box and not a numbered arrow, turning at right angles. It never crosses',
  '  itself and never enters an arrow cell.',
  '- A number with an arrow counts the boxes (shaded cells) along that arrow, to the edge of the board. Arrows can point along rows,',
  '  columns or, in some books, diagonals.',
  '- Boxes never touch each other along an edge.',
  '- A dot marks a cell you know is on the loop (not a box).',
  '',
  '## How the examples work',
  '',
  'Each picture is a position you reach by pressing **Hint** and marking what it says, over and over, from the empty board. Every picture',
  'shows the Hint button\'s own explanation and its colours: the cell being decided, the cells it looks at, and (dashed) the lines a',
  'trial box would force. The puzzles live in a book called **armory** that is not in the book picker; click any picture to open that',
  'puzzle in the app. Pressing Hint all the way through will show you the technique at the position pictured, and you can try the other',
  'moves along the way too.',
  '',
  'Techniques are listed from the one a person notices first to the one they notice last. That order is the rating system\'s: the solver',
  'always takes the cheapest rule that applies, and a puzzle\'s difficulty is the total cost of the steps it needs. The cost is shown',
  'beside each name.',
  '',
);

say('## Bookkeeping', '');
say('Three rules cost almost nothing and the hint never shows them: they tidy up what is already certain, so the other rules can look at a',
  'clean board.', '');
for (const r of RULES.filter((x) => x.free)) say(`- \`${r.id}\`: ${about[r.id] || r.label}`);
say('');

for (const tier of TIERS.filter((t) => RULES.some((r) => r.tier === t && !r.free))) {
  const info = TIER_INFO && TIER_INFO[tier];
  say(`## ${tier}`, '');
  if (info && info.blurb) say(`A puzzle is rated ${tier} when the hardest thing it needs is this: ${info.blurb}.`, '');
  for (const r of RULES.filter((x) => x.tier === tier && !x.free)) {
    say(`### ${r.id}`, '', `*${tier}, cost ${r.weight}*`, '');
    say(about[r.id] || cap(r.label), '');
    if (byRule.has(r.id)) say(...ex(r));
    else if (NO_EXAMPLE[r.id]) say(`*No picture: ${NO_EXAMPLE[r.id]}*`, '');
    say('---', '');
  }
}

fs.writeFileSync(root + 'docs/how_to_solve.md', out.join('\n').replace(/\n---\n\n$/, '\n'));
console.log(`docs/how_to_solve.md: ${out.length} lines, ${byRule.size} examples`);
